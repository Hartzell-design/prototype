#!/usr/bin/env node
// Northbridge design tokens: build tokens.css (+ Figma import files) from tokens.json.
// Usage: node build.mjs          write tokens.css and figma/*.json
//        node build.mjs --check  exit 1 if the files on disk differ from a fresh build
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const SRC = join(DIR, "tokens.json");
const PREFIX = "nb";
const SETS = { primitive: "primitive", current: "northbridge-2026", legacy: "legacy" };

/** Walk a DTCG tree and return [{path, token, type}] with $type inherited from groups. */
export function flatten(node, path = [], inherited) {
  const out = [];
  const type = node.$type ?? inherited;
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$") || v === null || typeof v !== "object") continue;
    if ("$value" in v) out.push({ path: [...path, k], token: v, type: v.$type ?? type });
    else out.push(...flatten(v, [...path, k], type));
  }
  return out;
}

const cssName = (path) => `--${PREFIX}-${path.join("-").replace(/\./g, "-")}`;
const ALIAS = /^\{([^{}]+)\}$/;
const ref = (v) => {
  const m = typeof v === "string" && v.match(ALIAS);
  return m ? `var(${cssName(m[1].split("."))})` : null;
};
const scalar = (v) => ref(v) ?? String(v);
const family = (v) => ref(v) ?? (Array.isArray(v) ? v : [v]).map((f) => (/^[\w-]+$/.test(f) ? f : `"${f}"`)).join(", ");
const shadow = (v) => ref(v) ?? (Array.isArray(v) ? v : [v])
  .map((s) => [s.inset ? "inset" : "", scalar(s.offsetX), scalar(s.offsetY), scalar(s.blur), scalar(s.spread), scalar(s.color)].filter(Boolean).join(" "))
  .join(", ");

/** Turn one token into one or more [name, cssValue] declarations. */
function declarations({ path, token, type }) {
  const v = token.$value, name = cssName(path);
  switch (type) {
    case "typography":
      if (ref(v)) return [[name, ref(v)]];
      return [
        [`${name}-font-family`, family(v.fontFamily)], [`${name}-font-size`, scalar(v.fontSize)],
        [`${name}-font-weight`, scalar(v.fontWeight)], [`${name}-line-height`, scalar(v.lineHeight)],
        [`${name}-letter-spacing`, scalar(v.letterSpacing)],
      ];
    case "shadow": return [[name, shadow(v)]];
    case "fontFamily": return [[name, family(v)]];
    case "cubicBezier": return [[name, ref(v) ?? `cubic-bezier(${v.join(", ")})`]];
    default: return [[name, scalar(v)]];
  }
}

function block(selector, tokens, comment) {
  const lines = tokens.flatMap(declarations).map(([n, v]) => `  ${n}: ${v};`);
  return `/* ${comment} */\n${selector} {\n${lines.join("\n")}\n}\n`;
}

export function build(doc) {
  const prim = flatten(doc[SETS.primitive]);
  const cur = flatten(doc[SETS.current]);
  const leg = flatten(doc[SETS.legacy]);
  const css =
    `/* Northbridge design tokens. GENERATED by build.mjs from tokens.json. Do not edit by hand. */\n` +
    `/* Default theme = northbridge-2026. Add data-theme="legacy" to any element for the pre-rebrand look. */\n\n` +
    block(":root", prim, "Primitives (shared by both versions)") + "\n" +
    block(":root", cur, "Semantic: northbridge-2026 (current)") + "\n" +
    block('[data-theme="legacy"]', leg, "Semantic: legacy (pre-rebrand)");
  // Figma native variable import: one plain DTCG file per collection mode.
  const figma = {
    "primitives.json": doc[SETS.primitive],
    "semantic.northbridge-2026.json": doc[SETS.current],
    "semantic.legacy.json": doc[SETS.legacy],
  };
  const files = { "tokens.css": css };
  for (const [f, tree] of Object.entries(figma)) files[`figma/${f}`] = JSON.stringify(tree, null, 2) + "\n";
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = build(JSON.parse(readFileSync(SRC, "utf8")));
  const check = process.argv.includes("--check");
  let stale = [];
  for (const [rel, text] of Object.entries(files)) {
    const p = join(DIR, rel);
    if (check) { if (!existsSync(p) || readFileSync(p, "utf8") !== text) stale.push(rel); }
    else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); }
  }
  if (check) {
    if (stale.length) { console.error("Out of date: " + stale.join(", ")); process.exit(1); }
    console.log("Up to date: " + Object.keys(files).join(", "));
  } else console.log("Wrote " + Object.keys(files).join(", "));
}
